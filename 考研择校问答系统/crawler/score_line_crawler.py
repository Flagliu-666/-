    def get_school_score_lines(self, school_name: str) -> Dict:
        """获取某校的分数线（自划线院校）"""
        self_drawn = self.get_self_drawn_schools()
        if school_name in self_drawn:
            return {
                '学校': school_name,
                '类型': '自主划线',
                '分数线': self_drawn[school_name]
            }
        else:
            return {
                '学校': school_name,
                '类型': '非自主划线',
                '分数线': '执行国家线',
                '备注': '具体分数线请参考学校研究生院官网'
            }
    
    def compare_score_lines(self, major: str, year: int = 2024) -> Dict:
        """对比某专业不同类型院校的分数线"""
        national = self.get_national_score_line(year)
        
        # 提取相关学科
        major_mapping = {
            '工科': '工学', '计算机': '工学', '软件': '工学',
            '理科': '理学', '物理': '理学', '数学': '理学',
            '文科': '文学', '中文': '文学', '历史': '历史学',
            '经济': '经济学', '金融': '经济学',
            '管理': '管理学', '会计': '管理学', '工商': '管理学',
            '法律': '法学', '医学': '医学', '教育': '教育学',
            '艺术': '艺术学', '哲学': '哲学',
        }
        
        category = None
        for key, value in major_mapping.items():
            if key in major:
                category = value
                break
        
        if not category:
            category = '工学'  # 默认
        
        national_a = national['A类'].get(category, national['A类']['工学'])
        
        return {
            '年份': year,
            '学科门类': category,
            'A类国家线': national_a,
            'B类国家线': national['B类'].get(category, national['B类']['工学']),
            '34所自划线': '通常是A类线的1.1-1.3倍',
            '备注': '实际分数线以学校公布为准'
        }
    
